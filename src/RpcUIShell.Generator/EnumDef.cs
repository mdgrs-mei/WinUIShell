using RpcUIShell.Core;

namespace RpcUIShell.Generator;

internal class EnumDef
{
    private readonly Api.EnumDef _apiEnumDef;

    public EnumDef(Api.EnumDef apiEnumDef)
    {
        _apiEnumDef = apiEnumDef;
    }

    public string GetSourceCodeFileName()
    {
        return $"{Generator.Api!.ModuleName}.{_apiEnumDef.Namespace}.{_apiEnumDef.Name}.g.cs";
    }

    public string Generate()
    {
        var codeWriter = new CodeWriter();

        var ns = Generator.GetTargetNamespace(_apiEnumDef.Namespace);

        codeWriter.Append($$"""
                // <auto-generated/>

                namespace {{ns}};

                """);

        Generate(codeWriter);

        return codeWriter.ToString();
    }

    public void Generate(CodeWriter codeWriter)
    {
        codeWriter.Append($$"""
                public enum {{_apiEnumDef.Name}} : global::System.{{_apiEnumDef.UnderlyingType}}
                {
                """);

        codeWriter.IncrementIndent();
        foreach (var item in _apiEnumDef.Entries)
        {
            codeWriter.Append($"{item.Name} = {item.Value},");
        }
        codeWriter.DecrementIndent();

        codeWriter.Append("}");
    }
}
